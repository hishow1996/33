private const val UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"

/** Shared extractor HTTP client: reuse connections and bound request duration. */
private val newPipeHttpClient = OkHttpClient.Builder()
    .connectTimeout(15, TimeUnit.SECONDS)
    .readTimeout(30, TimeUnit.SECONDS)
    .callTimeout(45, TimeUnit.SECONDS)
    .build()

private val extractorOwnerJob = ThreadLocal<Job?>()

/**
 * The extractor API is synchronous, but its request is owned by a cancellable coroutine.
 * Cancel the underlying OkHttp call while execute() or body consumption is blocked.
 */
@OptIn(kotlinx.coroutines.InternalCoroutinesApi::class)
internal fun <T> executeCancellableHttpCall(
    call: okhttp3.Call,
    ownerJob: Job?,
    consume: (okhttp3.Response) -> T,
): T {
    val cancellationHandle = ownerJob?.invokeOnCompletion(
        onCancelling = true,
        invokeImmediately = true,
    ) { cause ->
        if (cause is CancellationException) call.cancel()
    }
    try {
        return call.execute().use(consume)
    } catch (error: IOException) {
        if (ownerJob?.isCancelled == true) {
            throw kotlinx.coroutines.CancellationException("YouTube 请求已取消").also {
                it.initCause(error)
            }
        }
        throw error
    } finally {
        cancellationHandle?.dispose()
    }
}

/** NewPipe Extractor 网络层（okhttp 封装） */
object SimpleDownloader : Downloader() {

    override fun execute(r: Request): Response {
        val b = okhttp3.Request.Builder().url(r.url())
        r.headers().forEach { (k, v) -> b.header(k, v.joinToString(", ")) }
        if (r.headers().keys.none { it.equals("User-Agent", true) }) {
            b.header("User-Agent", UA)
        }
        when (r.httpMethod().uppercase()) {
            "POST" -> b.post(okhttp3.RequestBody.create(null, r.dataToSend() ?: ByteArray(0)))
            "HEAD" -> b.head()
            else -> b.get()
        }
        val ownerJob = extractorOwnerJob.get()
        return executeCancellableHttpCall(
            call = newPipeHttpClient.newCall(b.build()),
            ownerJob = ownerJob,
        ) { resp ->
            val responseBody = resp.body
            val responseText = if (responseBody == null) {
                ""
            } else {
                // NewPipe needs a String body, but never trust a remote Content-Length or
                // String() to bound memory on older phones. Apply a hard cap even for chunked
                // responses whose length is unknown.
                if (responseBody.contentLength() > BoundedTextPayload.MAX_BYTES) {
                    throw IllegalStateException("YouTube 响应超过 16 MB 限制，已停止读取以保护设备内存。")
                }
                String(
                    BoundedTextPayload.readBytes(
                        responseBody.byteStream(),
                        resourceLabel = "YouTube 响应",
                        checkActive = { ownerJob?.ensureActive() },
                    ),
                    Charsets.UTF_8,
                )
            }
            Response(
                resp.code, resp.message, resp.headers.toMultimap(),
                responseText, resp.request.url.toString()
            )
        }
    }
}

data class SubtitleTrackOption(
    val id: String,
    val languageTag: String,
    val isAutoGenerated: Boolean,
    val url: String,
)

object NewPipeRepo {
    @Volatile private var inited = false
    @Volatile private var cachedInfo: StreamInfo? = null
    @Volatile private var cachedId: String? = null
    private val infoLock = Any()
    /** Every invalidation prevents any older in-flight fetch from repopulating the cache. */
    private var infoCacheGeneration = 0L

    /** StreamInfo 复用：缓存读写有锁；网络解析不占用锁，避免卡住主线程的 invalidation。 */
    private suspend fun info(videoId: String): StreamInfo =
        kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
            val cached = synchronized(infoLock) {
                if (cachedId == videoId) cachedInfo else null
            }
            if (cached != null) return@withContext cached

            val requestGeneration = synchronized(infoLock) { infoCacheGeneration }
            initOnce()
            // This fetch is intentionally outside infoLock. Each caller returns its own result,
            // and a generation check prevents a stale fetch from being installed after invalidate().
            val ownerJob = currentCoroutineContext()[Job]
            val previousJob = extractorOwnerJob.get()
            if (ownerJob == null) extractorOwnerJob.remove() else extractorOwnerJob.set(ownerJob)
            val fetched = try {
                StreamInfo.getInfo(
                    ServiceList.YouTube,
                    "https://www.youtube.com/watch?v=$videoId",
                )
            } finally {
                if (previousJob == null) extractorOwnerJob.remove()
                else extractorOwnerJob.set(previousJob)
            }
            synchronized(infoLock) {
                if (infoCacheGeneration == requestGeneration) {
                    cachedInfo = fetched
                    cachedId = videoId
                }
            }
            fetched
        }

    fun init(@Suppress("UNUSED_PARAMETER") ctx: android.content.Context) {
        initOnce()
    }

    /** Explicit retry invalidates cached data without blocking on an in-flight network request. */
    fun invalidate(videoId: String? = null) {
        synchronized(infoLock) {
            infoCacheGeneration += 1
            if (videoId == null || cachedId == videoId) {
                cachedInfo = null
                cachedId = null
            }
        }
    }

    /** 从链接或原始 11 位 ID 提取 YouTube 视频 ID，并校验 URL 主机名。 */
    fun extractVideoId(text: String): String? = YouTubeUrlParser.extractVideoId(text)

    data class VideoMeta(
        val videoId: String, val url: String, val title: String,
        val channel: String, val durationSec: Long, val thumbUrl: String,
    )

    suspend fun resolve(videoId: String): VideoMeta {
        val info = info(videoId)
        return VideoMeta(
            videoId = videoId,
            url = "https://www.youtube.com/watch?v=$videoId",
            title = info.name ?: videoId,
            channel = info.uploaderName ?: "",
            durationSec = info.duration,
            thumbUrl = info.thumbnails.firstOrNull()?.url ?: "",
        )
    }

    /** 返回视频可用的全部字幕轨，给解析页展示；不下载任何字幕内容。 */
    suspend fun subtitleTracks(videoId: String): List<SubtitleTrackOption> {
        val tracks = try {
            info(videoId).subtitles
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (e: Exception) {
            android.util.Log.w("NewPipeRepo", "Could not list YouTube subtitle tracks", e)
            emptyList()
        }
        return tracks.mapIndexedNotNull { index, track ->
            val url = track.url?.takeIf { it.isNotBlank() } ?: return@mapIndexedNotNull null
            val kind = if (track.isAutoGenerated) "auto" else "manual"
            SubtitleTrackOption(
                id = index.toString() + "_" + track.languageTag + "_" + kind,
                languageTag = track.languageTag.ifBlank { "und" },
                isAutoGenerated = track.isAutoGenerated,
                url = url,
            )
        }.sortedBy { track ->
            val english = track.languageTag.startsWith("en", ignoreCase = true)
            when {
                !track.isAutoGenerated && english -> 0
                !track.isAutoGenerated -> 1
                english -> 2
                else -> 3
            }
        }
    }

    /** 下载单条字幕轨，优先取 WebVTT；不同源格式统一解析后再导出为 VTT。 */
    suspend fun downloadSubtitleContent(track: SubtitleTrackOption): String =
        kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
            val ownerJob = currentCoroutineContext()[Job]
            var lastError: Exception? = null
            val candidates = listOf(withSubtitleFormat(track.url, "vtt"), track.url).distinct()
            for (url in candidates) {
                try {
                    val body = downloadText(url)
                    val parsed = SubtitleParsers.parseAutoCancellable(body) {
                        ownerJob?.ensureActive()
                    }.filter { it.startMs >= 0L && it.endMs > it.startMs }
                    if (parsed.isNotEmpty()) return@withContext SubtitleParsers.toVtt(parsed)
                    lastError = IllegalStateException("字幕内容无法识别")
                } catch (e: kotlinx.coroutines.CancellationException) {
                    throw e
                } catch (e: Exception) {
                    lastError = e
                }
            }
            throw IllegalStateException(
                "无法下载该字幕轨" + (lastError?.message?.let { "：" + it } ?: ""),
                lastError,
            )
        }

    /** 字幕轨优先请求 WebVTT；NewPipe 默认 URL 常为 TTML，需兼容两种格式。 */
    suspend fun subtitles(videoId: String): Pair<List<SubLine>, String>? {
        val ownerJob = currentCoroutineContext()[Job]
        val streamInfo = info(videoId)
        val tracks: List<SubtitlesStream> = try {
            streamInfo.subtitles
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (e: Exception) {
            android.util.Log.w("NewPipeRepo", "Could not obtain YouTube subtitle tracks", e)
            emptyList()
        }
        if (tracks.isEmpty()) {
            android.util.Log.i("NewPipeRepo", "No YouTube subtitle tracks for video=$videoId")
            return null
        }

        // Prefer human English captions, then other human captions, then auto-generated tracks.
        val ordered = tracks.sortedBy { track ->
            val isEnglish = track.languageTag.startsWith("en", ignoreCase = true)
            when {
                !track.isAutoGenerated && isEnglish -> 0
                !track.isAutoGenerated -> 1
                isEnglish -> 2
                else -> 3
            }
        }

        for (track in ordered) {
            val url = track.url?.takeIf { it.isNotBlank() } ?: continue
            val candidateUrls = listOf(withSubtitleFormat(url, "vtt"), url).distinct()
            for (candidateUrl in candidateUrls) {
                try {
                    val body = downloadText(candidateUrl)
                    val lines = SubtitleParsers.parseAutoCancellable(body) {
                        ownerJob?.ensureActive()
                    }
                    if (lines.isNotEmpty()) {
                        android.util.Log.i(
                            "NewPipeRepo",
                            "Loaded ${lines.size} subtitle cues (language=${track.languageTag}, auto=${track.isAutoGenerated})"
                        )
                        return lines to track.languageTag
                    }
                    android.util.Log.w(
                        "NewPipeRepo",
                        "Subtitle response could not be parsed as cues (formatUrl=${candidateUrl.contains("fmt=vtt")})"
                    )
                } catch (e: kotlinx.coroutines.CancellationException) {
                    throw e
                } catch (e: Exception) {
                    android.util.Log.w(
                        "NewPipeRepo",
                        "Subtitle track request failed (language=${track.languageTag}, auto=${track.isAutoGenerated})",
                        e
                    )
                }
            }
        }
        android.util.Log.w(
            "NewPipeRepo",
            "Found ${tracks.size} subtitle tracks but none could be downloaded or parsed for video=$videoId"
        )
        return null
    }

    private fun withSubtitleFormat(url: String, format: String): String {
        val formatParam = Regex("([?&])fmt=[^&]*")
        return if (formatParam.containsMatchIn(url)) {
            formatParam.replace(url) { "${it.groupValues[1]}fmt=$format" }
        } else {
            url + if (url.contains("?")) "&fmt=$format" else "?fmt=$format"
        }
    }

    /** 播放用：完整 StreamInfo（videoOnly/muxed/audio 由上层挑） */
    suspend fun streams(videoId: String): StreamInfo = info(videoId)

    /** 转写用音频流：优先 M4A 的最低有效码率，减少下载时间与缓存占用。 */
    suspend fun audioForAsr(videoId: String): AudioStream? {
        val streams = info(videoId).audioStreams
        val candidates = streams.map { stream ->
            YouTubeAudioCandidate(
                url = stream.content,
                formatSuffix = if (stream.format == org.schabi.newpipe.extractor.MediaFormat.M4A) {
                    "m4a"
                } else {
                    stream.format?.suffix
                },
                bitrate = stream.averageBitrate,
            )
        }
        val selectedIndex = YouTubeStreamSelector.chooseAudioStreamForAsrIndex(candidates)
        return streams.getOrNull(selectedIndex)
    }

    private suspend fun downloadText(url: String): String = withContext(Dispatchers.IO) {
        val req = okhttp3.Request.Builder().url(url).header("User-Agent", UA).build()
        val ownerJob = currentCoroutineContext()[Job]
        executeCancellableHttpCall(newPipeHttpClient.newCall(req), ownerJob) { resp ->
            if (!resp.isSuccessful) throw IllegalStateException("字幕下载失败 ${resp.code}")
            val body = resp.body ?: return@executeCancellableHttpCall ""
            if (body.contentLength() > BoundedTextPayload.MAX_BYTES) {
                throw IllegalStateException("字幕响应超过 16 MB 限制，已停止读取以保护设备内存。")
            }
            val bytes = body.byteStream().use { input ->
                BoundedTextPayload.readBytes(
                    input,
                    resourceLabel = "YouTube 字幕响应",
                    checkActive = { ownerJob?.ensureActive() },
                )
            }
            String(bytes, Charsets.UTF_8)
        }
    }

    private fun initOnce() {
        if (!inited) {
            synchronized(this) {
                if (!inited) {
                    org.schabi.newpipe.extractor.NewPipe.init(SimpleDownloader)
                    inited = true
                }
            }
        }
    }
}
