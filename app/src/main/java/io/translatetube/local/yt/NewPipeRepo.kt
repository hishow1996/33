import org.schabi.newpipe.extractor.stream.SubtitlesStream
import java.util.concurrent.TimeUnit

private const val UA = "Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0.0.0 Safari/537.36"

/** NewPipe Extractor 网络层（okhttp 封装） */
object SimpleDownloader : Downloader() {
    private val client = OkHttpClient.Builder()
        .connectTimeout(15, TimeUnit.SECONDS)
        .readTimeout(30, TimeUnit.SECONDS)
        .build()

    override fun execute(r: Request): Response {
        val b = okhttp3.Request.Builder().url(r.url())
        r.headers().forEach { (k, v) -> b.header(k, v.joinToString(", ")) }
        if (r.headers().keys.none { it.equals("User-Agent", true) }) {
            b.header("User-Agent", UA)
        }
        when (r.httpMethod().uppercase()) {
            "POST" -> b.post(okhttp3.RequestBody.create(null, r.dataToSend() ?: ByteArray(0)))
            "HEAD" -> b.head()
            else -> b.get()
        }
        client.newCall(b.build()).execute().use { resp ->
            return Response(
                resp.code, resp.message, resp.headers.toMultimap(),
                resp.body?.string() ?: "", resp.request.url.toString()
            )
        }
    }
}

data class SubtitleTrackOption(
    val id: String,
    val languageTag: String,
    val isAutoGenerated: Boolean,
    val url: String,
)

object NewPipeRepo {
    @Volatile private var inited = false
    @Volatile private var cachedInfo: StreamInfo? = null
    @Volatile private var cachedId: String? = null

    /** StreamInfo 复用：一次解析，字幕/流/元信息共享，避免对 YouTube 三连击 */
    private suspend fun info(videoId: String): StreamInfo =
        kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
            if (cachedId == videoId && cachedInfo != null) return@withContext cachedInfo!!
            initOnce()
            // Use the regular watch endpoint for all video IDs (including Shorts IDs). This exposes
            // the normal adaptiveFormats/videoOnlyStreams data used by the quality selector.
            val i = StreamInfo.getInfo(ServiceList.YouTube, "https://www.youtube.com/watch?v=$videoId")
            cachedInfo = i
            cachedId = videoId
            i
        }

    fun init(@Suppress("UNUSED_PARAMETER") ctx: android.content.Context) {
        initOnce()
    }

    /** Explicit retry must discard stale/partial extraction results and fetch fresh YouTube metadata. */
    fun invalidate(videoId: String? = null) {
        synchronized(this) {
            if (videoId == null || cachedId == videoId) {
                cachedInfo = null
                cachedId = null
            }
        }
    }

    /** 从任意文本提取 YouTube 视频 id */
    fun extractVideoId(text: String): String? {
        val u = text.trim()
        Regex("(?:v=|/shorts/|youtu\\.be/|/embed/)([A-Za-z0-9_-]{11})")
            .find(u)?.let { return it.groupValues[1] }
        if (Regex("^[A-Za-z0-9_-]{11}$").matches(u)) return u
        return null
    }

    data class VideoMeta(
        val videoId: String, val url: String, val title: String,
        val channel: String, val durationSec: Long, val thumbUrl: String,
    )

    suspend fun resolve(videoId: String): VideoMeta {
        val info = info(videoId)
        return VideoMeta(
            videoId = videoId,
            url = "https://www.youtube.com/watch?v=$videoId",
            title = info.name ?: videoId,
            channel = info.uploaderName ?: "",
            durationSec = info.duration,
            thumbUrl = info.thumbnails.firstOrNull()?.url ?: "",
        )
    }

    /** 返回视频可用的全部字幕轨，给解析页展示；不下载任何字幕内容。 */
    suspend fun subtitleTracks(videoId: String): List<SubtitleTrackOption> {
        val tracks = try {
            info(videoId).subtitles
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (e: Exception) {
            android.util.Log.w("NewPipeRepo", "Could not list YouTube subtitle tracks", e)
            emptyList()
        }
        return tracks.mapIndexedNotNull { index, track ->
            val url = track.url?.takeIf { it.isNotBlank() } ?: return@mapIndexedNotNull null
            val kind = if (track.isAutoGenerated) "auto" else "manual"
            SubtitleTrackOption(
                id = index.toString() + "_" + track.languageTag + "_" + kind,
                languageTag = track.languageTag.ifBlank { "und" },
                isAutoGenerated = track.isAutoGenerated,
                url = url,
            )
        }.sortedBy { track ->
            val english = track.languageTag.startsWith("en", ignoreCase = true)
            when {
                !track.isAutoGenerated && english -> 0
                !track.isAutoGenerated -> 1
                english -> 2
                else -> 3
            }
        }
    }

    /** 下载单条字幕轨，优先取 WebVTT；不同源格式统一解析后再导出为 VTT。 */
    suspend fun downloadSubtitleContent(track: SubtitleTrackOption): String =
        kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
            var lastError: Exception? = null
            val candidates = listOf(withSubtitleFormat(track.url, "vtt"), track.url).distinct()
            for (url in candidates) {
                try {
                    val body = downloadText(url)
                    val parsed = SubtitleParsers.parseAuto(body)
                        .filter { it.startMs >= 0L && it.endMs > it.startMs }
                    if (parsed.isNotEmpty()) return@withContext SubtitleParsers.toVtt(parsed)
                    lastError = IllegalStateException("字幕内容无法识别")
                } catch (e: kotlinx.coroutines.CancellationException) {
                    throw e
                } catch (e: Exception) {
                    lastError = e
                }
            }
            throw IllegalStateException(
                "无法下载该字幕轨" + (lastError?.message?.let { "：" + it } ?: ""),
                lastError,
            )
        }

    /** 字幕轨优先请求 WebVTT；NewPipe 默认 URL 常为 TTML，需兼容两种格式。 */
    suspend fun subtitles(videoId: String): Pair<List<SubLine>, String>? {
        val streamInfo = info(videoId)
        val tracks: List<SubtitlesStream> = try {
            streamInfo.subtitles
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (e: Exception) {
            android.util.Log.w("NewPipeRepo", "Could not obtain YouTube subtitle tracks", e)
            emptyList()
        }
        if (tracks.isEmpty()) {
            android.util.Log.i("NewPipeRepo", "No YouTube subtitle tracks for video=$videoId")
            return null
        }

        // Prefer human English captions, then other human captions, then auto-generated tracks.
        val ordered = tracks.sortedBy { track ->
            val isEnglish = track.languageTag.startsWith("en", ignoreCase = true)
            when {
                !track.isAutoGenerated && isEnglish -> 0
                !track.isAutoGenerated -> 1
                isEnglish -> 2
                else -> 3
            }
        }

        for (track in ordered) {
            val url = track.url?.takeIf { it.isNotBlank() } ?: continue
            val candidateUrls = listOf(withSubtitleFormat(url, "vtt"), url).distinct()
            for (candidateUrl in candidateUrls) {
                try {
                    val body = downloadText(candidateUrl)
                    val lines = SubtitleParsers.parseAuto(body)
                    if (lines.isNotEmpty()) {
                        android.util.Log.i(
                            "NewPipeRepo",
                            "Loaded ${lines.size} subtitle cues (language=${track.languageTag}, auto=${track.isAutoGenerated})"
                        )
                        return lines to track.languageTag
                    }
                    android.util.Log.w(
                        "NewPipeRepo",
                        "Subtitle response could not be parsed as cues (formatUrl=${candidateUrl.contains("fmt=vtt")})"
                    )
                } catch (e: kotlinx.coroutines.CancellationException) {
                    throw e
                } catch (e: Exception) {
                    android.util.Log.w(
                        "NewPipeRepo",
                        "Subtitle track request failed (language=${track.languageTag}, auto=${track.isAutoGenerated})",
                        e
                    )
                }
            }
        }
        android.util.Log.w(
            "NewPipeRepo",
            "Found ${tracks.size} subtitle tracks but none could be downloaded or parsed for video=$videoId"
        )
        return null
    }

    private fun withSubtitleFormat(url: String, format: String): String {
        val formatParam = Regex("([?&])fmt=[^&]*")
        return if (formatParam.containsMatchIn(url)) {
            formatParam.replace(url) { "${it.groupValues[1]}fmt=$format" }
        } else {
            url + if (url.contains("?")) "&fmt=$format" else "?fmt=$format"
        }
    }

    /** 播放用：完整 StreamInfo（videoOnly/muxed/audio 由上层挑） */
    suspend fun streams(videoId: String): StreamInfo = info(videoId)

    /** 转写用音频流（挑最小比特率） */
    suspend fun audioForAsr(videoId: String): AudioStream? {
        val info = info(videoId)
        val streams = info.audioStreams
        // 优先 m4a（MediaExtractor 解码最稳），退而求其次选任意最小码率流
        return streams.firstOrNull { s ->
            s.format == org.schabi.newpipe.extractor.MediaFormat.M4A ||
                s.format?.suffix == "m4a"
        } ?: streams.minByOrNull { it.averageBitrate }
    }

    private fun downloadText(url: String): String {
        val req = okhttp3.Request.Builder().url(url).header("User-Agent", UA).build()
        OkHttpClient().newCall(req).execute().use { resp ->
            if (!resp.isSuccessful) throw IllegalStateException("字幕下载失败 ${resp.code}")
            return resp.body?.string() ?: ""
        }
    }

    private fun initOnce() {
        if (!inited) {
            synchronized(this) {
                if (!inited) {
                    org.schabi.newpipe.extractor.NewPipe.init(SimpleDownloader)
                    inited = true
                }
            }
        }
    }
}
