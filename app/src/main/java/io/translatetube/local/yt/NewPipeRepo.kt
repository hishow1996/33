    private fun selectedSubtitleLanguageMode(): YouTubeSubtitleLanguageMode =
        YouTubeSubtitleSelectionPolicy.modeFromPreference(
            appContext?.getSharedPreferences("settings", Context.MODE_PRIVATE)
                ?.getString(
                    YouTubeSubtitleSelectionPolicy.PREF_KEY,
                    YouTubeSubtitleSelectionPolicy.DEFAULT_MODE,
                ),
        )

    private fun subtitleLanguageDisplayName(languageTag: String?): String =
        when (YouTubeSubtitleSelectionPolicy.normalizeLanguageCode(languageTag)) {
            "en" -> "英语"
            "ko" -> "韩语"
            "ja" -> "日语"
            "zh" -> "中文"
            "ru" -> "俄语"
            "fr" -> "法语"
            "de" -> "德语"
            "es" -> "西班牙语"
            "pt" -> "葡萄牙语"
            "it" -> "意大利语"
            "ar" -> "阿拉伯语"
            "hi" -> "印地语"
            "th" -> "泰语"
            "vi" -> "越南语"
            "id" -> "印尼语"
            "nl" -> "荷兰语"
            "pl" -> "波兰语"
            "tr" -> "土耳其语"
            "uk" -> "乌克兰语"
            "sv" -> "瑞典语"
            "da" -> "丹麦语"
            "fi" -> "芬兰语"
            else -> languageTag?.takeIf { it.isNotBlank() } ?: "未知语言"
        }

    private fun subtitleFallbackStatus(
        mode: YouTubeSubtitleLanguageMode,
        tier: Int,
        sourceLanguageTag: String?,
        selectedLanguageTag: String?,
    ): String {
        val selected = subtitleLanguageDisplayName(selectedLanguageTag)
        val source = subtitleLanguageDisplayName(sourceLanguageTag)
        return when (mode) {
            YouTubeSubtitleLanguageMode.PREFER_ENGLISH -> when (tier) {
                1 -> "英语字幕不可用，正在尝试${selected}原声字幕"
                else -> if (sourceLanguageTag != null) {
                    "英语和${source}原声字幕不可用，正在尝试${selected}字幕"
                } else {
                    "英语字幕不可用，正在尝试其他语言字幕（${selected}）"
                }
            }
            YouTubeSubtitleLanguageMode.MATCH_ORIGINAL -> when (tier) {
                1 -> if (sourceLanguageTag != null) {
                    "${source}原声字幕不可用，正在尝试${selected}字幕"
                } else {
                    "无法确认原声语言字幕，正在尝试${selected}字幕"
                }
                else -> if (sourceLanguageTag != null) {
                    "${source}原声和英语字幕不可用，正在尝试${selected}字幕"
                } else {
                    "无法确认原声字幕且英语字幕不可用，正在尝试${selected}字幕"
                }
            }
        }
    }

    /** 返回视频可用的全部字幕轨，给解析页展示；不下载任何字幕内容。 */
    suspend fun subtitleTracks(videoId: String): List<SubtitleTrackOption> {
        var tracksReadSuccessfully = true
        var sourceLanguageTag: String? = null
        val tracks = try {
            val streamInfo = info(videoId)
            sourceLanguageTag = sourceLanguageHint(streamInfo)
            streamInfo.subtitles
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (e: Exception) {
            tracksReadSuccessfully = false
            android.util.Log.w("NewPipeRepo", "Could not list YouTube subtitle tracks", e)
            logWarning(
                "YouTube 字幕轨列表读取失败",
                e,
                mapOf("YouTube 视频 ID" to videoId, "失败阶段" to "读取元数据中的 subtitles 字段"),
            )
            emptyList()
        }
        val subtitleMode = selectedSubtitleLanguageMode()
        val options = tracks.mapIndexedNotNull { index, track ->
            val url = track.url?.takeIf { it.isNotBlank() } ?: return@mapIndexedNotNull null
            val kind = if (track.isAutoGenerated) "auto" else "manual"
            SubtitleTrackOption(
                id = index.toString() + "_" + track.languageTag + "_" + kind,
                languageTag = track.languageTag.ifBlank { "und" },
                isAutoGenerated = track.isAutoGenerated,
                url = url,
            )
        }.sortedBy { track ->
            YouTubeSubtitleSelectionPolicy.rank(
                sourceLanguageTag = sourceLanguageTag,
                subtitleLanguageTag = track.languageTag,
                isAutoGenerated = track.isAutoGenerated,
                mode = subtitleMode,
            )
        }
        if (tracksReadSuccessfully) {
            logInfo(
                "YouTube 字幕轨识别完成",
                mapOf(
                    "YouTube 视频 ID" to videoId,
                    "识别到的字幕轨数量" to options.size.toString(),
                    "手动字幕轨数量" to options.count { !it.isAutoGenerated }.toString(),
                    "自动生成字幕轨数量" to options.count { it.isAutoGenerated }.toString(),
                    "可用语言列表" to options.map { it.languageTag }.distinct().take(20).joinToString(", ").ifBlank { "无" },
                    "原声音频语言提示" to sourceLanguageTag.orEmpty().ifBlank { "未知" },
                    "字幕语言模式" to if (subtitleMode == YouTubeSubtitleLanguageMode.PREFER_ENGLISH) "英语优先，原声与其他字幕回退" else "原声优先，英语与其他字幕回退",
                    "字幕排序策略" to if (subtitleMode == YouTubeSubtitleLanguageMode.PREFER_ENGLISH) "英语人工/自动、原声人工/自动、其他人工/自动" else "原声人工/自动、英语人工/自动、其他人工/自动",
                ),
            )
        }
        return options
    }

    /** 下载单条字幕轨，优先取 WebVTT；不同源格式统一解析后再导出为 VTT。 */
    suspend fun downloadSubtitleContent(track: SubtitleTrackOption): String =
        kotlinx.coroutines.withContext(kotlinx.coroutines.Dispatchers.IO) {
            val ownerJob = currentCoroutineContext()[Job]
            var lastError: Exception? = null
            val candidates = listOf(withSubtitleFormat(track.url, "vtt"), track.url).distinct()
            for (url in candidates) {
                try {
                    val body = downloadText(url)
                    val parsed = SubtitleParsers.parseAutoCancellable(body) {
                        ownerJob?.ensureActive()
                    }.filter { it.startMs >= 0L && it.endMs > it.startMs }
                    if (parsed.isNotEmpty()) {
                        logInfo(
                            "YouTube 指定字幕轨下载与解析成功",
                            mapOf(
                                "字幕语言" to track.languageTag,
                                "是否自动生成" to track.isAutoGenerated.toString(),
                                "有效字幕行数" to parsed.size.toString(),
                                "原始字幕响应字符数" to body.length.toString(),
                                "实际采用 VTT 格式请求" to url.contains("fmt=vtt").toString(),
                                "尝试 URL 格式数量" to candidates.size.toString(),
                            ),
                        )
                        return@withContext SubtitleParsers.toVtt(parsed)
                    }
                    lastError = IllegalStateException("字幕内容无法识别")
                } catch (e: kotlinx.coroutines.CancellationException) {
                    throw e
                } catch (e: Exception) {
                    lastError = e
                }
            }
            val failure = IllegalStateException(
                "无法下载该字幕轨" + (lastError?.message?.let { "：" + it } ?: ""),
                lastError,
            )
            logError(
                "YouTube 指定字幕轨下载或解析失败",
                failure,
                mapOf(
                    "字幕语言" to track.languageTag,
                    "是否自动生成" to track.isAutoGenerated.toString(),
                    "尝试 URL 格式数量" to candidates.size.toString(),
                    "失败类型" to (lastError?.javaClass?.name ?: "未知"),
                ),
            )
            throw failure
        }

    /** 字幕轨优先请求 WebVTT；NewPipe 默认 URL 常为 TTML，需兼容两种格式。 */
    suspend fun subtitles(
        videoId: String,
        onFallback: suspend (String) -> Unit = {},
    ): Pair<List<SubLine>, String>? {
        val ownerJob = currentCoroutineContext()[Job]
        val streamInfo = info(videoId)
        val tracks: List<SubtitlesStream> = try {
            streamInfo.subtitles
        } catch (e: kotlinx.coroutines.CancellationException) {
            throw e
        } catch (e: Exception) {
            android.util.Log.w("NewPipeRepo", "Could not obtain YouTube subtitle tracks", e)
            emptyList()
        }
        if (tracks.isEmpty()) {
            android.util.Log.i("NewPipeRepo", "No YouTube subtitle tracks for video=$videoId")
            logWarning(
                "YouTube 视频没有可用字幕轨",
                context = mapOf(
                    "YouTube 视频 ID" to videoId,
                    "字幕轨数量" to "0",
                    "后续建议" to "由视频处理流程选择音轨提取与语音转写",
                ),
            )
            return null
        }

        val sourceLanguageTag = sourceLanguageHint(streamInfo)
        val subtitleMode = selectedSubtitleLanguageMode()
        val ordered = tracks.sortedBy { track ->
            YouTubeSubtitleSelectionPolicy.rank(
                sourceLanguageTag = sourceLanguageTag,
                subtitleLanguageTag = track.languageTag,
                isAutoGenerated = track.isAutoGenerated,
                mode = subtitleMode,
            )
        }
        // Try every available caption in preference order. English-first mode ranks English
        // captions first, then original-language captions, then all other captions. Original-first
        // mode reverses the first two priorities. Audio transcription is reached only if no
        // subtitle track can be downloaded and parsed successfully.
        val candidateTracks = ordered.filter { track -> !track.url.isNullOrBlank() }
        if (candidateTracks.isEmpty()) {
            logWarning(
                "YouTube 没有可下载的字幕轨，改用音频转写",
                context = mapOf(
                    "YouTube 视频 ID" to videoId,
                    "检测到字幕轨数量" to tracks.size.toString(),
                    "字幕语言模式" to if (subtitleMode == YouTubeSubtitleLanguageMode.PREFER_ENGLISH) "默认英语优先" else "原声语言优先",
                    "原声音频语言提示" to sourceLanguageTag.orEmpty().ifBlank { "未知" },
                    "识别到的字幕语言" to ordered.map { it.languageTag }.distinct().take(20).joinToString(", ").ifBlank { "无" },
                    "后续处理" to "没有带有效地址的字幕轨，改用视频音轨转写",
                ),
            )
            return null
        }

        var previousTier: Int? = null
        var previousLanguageCode: String? = null
        for (track in candidateTracks) {
            val url = track.url?.takeIf { it.isNotBlank() } ?: continue
            val tier = YouTubeSubtitleSelectionPolicy.priorityTier(
                sourceLanguageTag = sourceLanguageTag,
                subtitleLanguageTag = track.languageTag,
                mode = subtitleMode,
            )
            val languageCode = YouTubeSubtitleSelectionPolicy.normalizeLanguageCode(track.languageTag)
            when {
                previousTier == null && tier > 0 -> onFallback(
                    subtitleFallbackStatus(subtitleMode, tier, sourceLanguageTag, track.languageTag),
                )
                previousTier != null && tier > previousTier!! -> onFallback(
                    subtitleFallbackStatus(subtitleMode, tier, sourceLanguageTag, track.languageTag),
                )
                tier == 2 && previousTier == 2 &&
                    languageCode != null && previousLanguageCode != null &&
                    languageCode != previousLanguageCode -> onFallback(
                        "${subtitleLanguageDisplayName(previousLanguageCode)}字幕不可用，正在尝试${subtitleLanguageDisplayName(track.languageTag)}字幕",
                    )
            }
            previousTier = tier
            previousLanguageCode = languageCode
            val candidateUrls = listOf(withSubtitleFormat(url, "vtt"), url).distinct()
            for (candidateUrl in candidateUrls) {
                try {
                    val body = downloadText(candidateUrl)
                    val lines = SubtitleParsers.parseAutoCancellable(body) {
                        ownerJob?.ensureActive()
                    }
                    if (lines.isNotEmpty()) {
                        android.util.Log.i(
                            "NewPipeRepo",
                            "Loaded ${lines.size} subtitle cues (language=${track.languageTag}, auto=${track.isAutoGenerated})"
                        )
                        logInfo(
                            "YouTube 原字幕获取成功",
                            mapOf(
                                "YouTube 视频 ID" to videoId,
                                "选中字幕语言" to track.languageTag.ifBlank { "未知" },
                                "字幕语言模式" to if (subtitleMode == YouTubeSubtitleLanguageMode.PREFER_ENGLISH) "英语优先，原声与其他字幕回退" else "原声优先，英语与其他字幕回退",
                                "原声音频语言提示" to sourceLanguageTag.orEmpty().ifBlank { "未知" },
                                "字幕与原声语言匹配" to (
                                    YouTubeSubtitleSelectionPolicy.normalizeLanguageCode(track.languageTag) != null &&
                                        YouTubeSubtitleSelectionPolicy.normalizeLanguageCode(track.languageTag) ==
                                        YouTubeSubtitleSelectionPolicy.normalizeLanguageCode(sourceLanguageTag)
                                    ).toString(),
                                "是否自动生成" to track.isAutoGenerated.toString(),
                                "有效字幕行数" to lines.size.toString(),
                                "尝试过的字幕轨数量" to (candidateTracks.indexOf(track) + 1).toString(),
                                "当前使用 VTT 格式候选" to candidateUrl.contains("fmt=vtt").toString(),
                            ),
                        )
                        return lines to track.languageTag
                    }
                    android.util.Log.w(
                        "NewPipeRepo",
                        "Subtitle response could not be parsed as cues (formatUrl=${candidateUrl.contains("fmt=vtt")})"
                    )
                } catch (e: kotlinx.coroutines.CancellationException) {
                    throw e
                } catch (e: Exception) {
                    android.util.Log.w(
                        "NewPipeRepo",
                        "Subtitle track request failed (language=${track.languageTag}, auto=${track.isAutoGenerated})",
                        e
                    )
                }
            }
        }
        android.util.Log.w(
            "NewPipeRepo",
            "Found ${candidateTracks.size} eligible subtitle tracks but none could be downloaded or parsed for video=$videoId"
        )
        logWarning(
            "YouTube 存在字幕轨但全部下载或解析失败",
            context = mapOf(
                "YouTube 视频 ID" to videoId,
                "检测到字幕轨数量" to tracks.size.toString(),
                "字幕语言模式" to if (subtitleMode == YouTubeSubtitleLanguageMode.PREFER_ENGLISH) "英语优先，原声与其他字幕回退" else "原声优先，英语与其他字幕回退",
                "尝试过的字幕语言" to candidateTracks.map { it.languageTag }.distinct().take(20).joinToString(", "),
                "尝试格式" to "每条字幕轨优先 VTT，失败后重试原始格式",
                "后续建议" to "字幕轨已全部尝试但无法读取，后续由五阶段流程转写原声音轨",
            ),
        )
        return null
    }

    /**
     * Resolve the spoken source language from explicit ORIGINAL audio-track metadata first.
     * Stream-level language and non-dubbed audio locales are fallbacks for videos whose extractor
     * response does not expose the original-track marker.
     */
    private fun sourceLanguageHint(streamInfo: StreamInfo): String? {
        val audioStreams = runCatching { streamInfo.audioStreams }.getOrDefault(emptyList())
        val originalAudioTracks = audioStreams.filter { it.audioTrackType == AudioTrackType.ORIGINAL }
        val originalAudioLanguages = originalAudioTracks
            .mapNotNull { it.audioLocale?.toLanguageTag() }
        val fallbackAudioLanguages = audioStreams.asSequence()
            .filter {
                it.audioTrackType == null ||
                    it.audioTrackType == AudioTrackType.ORIGINAL
            }
            .mapNotNull { it.audioLocale?.toLanguageTag() }
            .toList()
        val streamLanguage = runCatching { streamInfo.languageInfo?.toLanguageTag() }.getOrNull()
        return YouTubeSubtitleSelectionPolicy.sourceLanguageHint(
            originalAudioLanguageTags = originalAudioLanguages,
            streamLanguageTag = streamLanguage,
            fallbackAudioLanguageTags = fallbackAudioLanguages,
            originalAudioTrackPresent = originalAudioTracks.isNotEmpty(),
        )
    }

    private fun withSubtitleFormat(url: String, format: String): String {
        val formatParam = Regex("([?&])fmt=[^&]*")
        return if (formatParam.containsMatchIn(url)) {
            formatParam.replace(url) { "${it.groupValues[1]}fmt=$format" }
        } else {
            url + if (url.contains("?")) "&fmt=$format" else "?fmt=$format"
        }
    }

    /** 播放用：完整 StreamInfo（videoOnly/muxed/audio 由上层挑） */
    suspend fun streams(videoId: String): StreamInfo = info(videoId)

    /** 暴露原声音轨语言提示，供播放流程检查旧字幕/转写缓存是否与原声语言一致。 */
    suspend fun sourceAudioLanguageHint(videoId: String): String? =
        sourceLanguageHint(info(videoId))

    /** Reuse the exact source-language policy when selecting the playback audio for known metadata. */
    internal fun sourceAudioLanguageHint(streamInfo: StreamInfo): String? =
        sourceLanguageHint(streamInfo)

    /** 转写用音频流：优先 M4A 的最低有效码率，减少下载时间与缓存占用。 */
    suspend fun audioForAsr(videoId: String): AudioStream? {
        val streamInfo = info(videoId)
        val streams = streamInfo.audioStreams
        val preferredLanguage = sourceLanguageHint(streamInfo)
        val candidates = streams.map { stream ->
            YouTubeAudioCandidate(
                url = stream.content,
                formatSuffix = if (stream.format == org.schabi.newpipe.extractor.MediaFormat.M4A) {
                    "m4a"
                } else {
                    stream.format?.suffix
                },
                bitrate = stream.averageBitrate,
                languageTag = stream.audioLocale?.toLanguageTag(),
                isOriginal = stream.audioTrackType == AudioTrackType.ORIGINAL,
                isDubbed = stream.audioTrackType == AudioTrackType.DUBBED,
                isDescriptive = stream.audioTrackType == AudioTrackType.DESCRIPTIVE,
                isSecondary = stream.audioTrackType == AudioTrackType.SECONDARY,
            )
        }
        val selectedIndex = YouTubeStreamSelector.chooseAudioStreamForAsrIndex(
            input = candidates,
            preferredLanguageTag = preferredLanguage,
        )
        val selected = streams.getOrNull(selectedIndex)
        if (selected == null) {
            val explicitOriginalLanguages = candidates.asSequence()
                .filter { it.isOriginal }
                .mapNotNull { YouTubeSubtitleSelectionPolicy.normalizeLanguageCode(it.languageTag) }
                .distinct()
                .toList()
            val candidateLanguages = candidates.mapNotNull {
                YouTubeSubtitleSelectionPolicy.normalizeLanguageCode(it.languageTag)
            }.distinct()
            val hasNonDubbedTrack = candidates.any { !it.isDubbed && !it.isDescriptive }
            val failureReason = when {
                explicitOriginalLanguages.size > 1 -> "原声音轨语言信息互相冲突"
                !hasNonDubbedTrack && candidates.isNotEmpty() -> "只找到配音轨或描述音轨"
                preferredLanguage == null && candidateLanguages.size > 1 ->
                    "发现多种音轨语言，但未找到可靠的原声标记"
                candidates.isEmpty() -> "没有有效的 HTTP 音轨地址"
                else -> "无法确定安全的原声转写音轨"
            }
            logWarning(
                "YouTube 转写音轨选择失败：拒绝猜选可能不是原声的音轨",
                context = mapOf(
                    "YouTube 视频 ID" to videoId,
                    "识别到音轨候选数量" to streams.size.toString(),
                    "原声音轨语言提示" to preferredLanguage.orEmpty().ifBlank { "未知" },
                    "检测到的音轨语言" to candidateLanguages.joinToString(", ").ifBlank { "未知" },
                    "明确标记的原声音轨语言" to explicitOriginalLanguages.joinToString(", ").ifBlank { "未知" },
                    "是否存在非配音/非描述音轨" to hasNonDubbedTrack.toString(),
                    "选择失败原因" to failureReason,
                ),
            )
        } else {
            logInfo(
                "YouTube 转写音轨选择完成",
                mapOf(
                    "YouTube 视频 ID" to videoId,
                    "识别到音轨候选数量" to streams.size.toString(),
                    "最终选中音轨序号" to (selectedIndex + 1).toString(),
                    "最终选中音轨格式" to (selected.format?.suffix ?: "未知"),
                    "最终选中音轨码率 kbps" to selected.averageBitrate.toString(),
                    "原声音轨语言" to preferredLanguage.orEmpty().ifBlank { "未知" },
                    "选中音轨语言" to selected.audioLocale?.toLanguageTag().orEmpty().ifBlank { "未知" },
                    "选中音轨是否原声" to (selected.audioTrackType == AudioTrackType.ORIGINAL).toString(),
                    "选中音轨是否配音" to (selected.audioTrackType == AudioTrackType.DUBBED).toString(),
                    "选择策略" to "先匹配明确原声音轨/语言，再在候选中优先低码率 M4A",
                ),
            )
        }
        return selected
    }

    private suspend fun downloadText(url: String): String = withContext(Dispatchers.IO) {
        val req = okhttp3.Request.Builder().url(url).header("User-Agent", UA).build()
        val ownerJob = currentCoroutineContext()[Job]
        executeCancellableHttpCall(newPipeHttpClient.newCall(req), ownerJob) { resp ->
            if (!HttpDownloadResponsePolicy.isCompleteGetResponse(resp.code)) {
                throw IllegalStateException("字幕下载需要完整 HTTP 200 响应，收到 HTTP ${resp.code}")
            }
            val body = resp.body ?: return@executeCancellableHttpCall ""
            if (body.contentLength() > BoundedTextPayload.MAX_BYTES) {
                throw IllegalStateException("字幕响应超过 16 MB 限制，已停止读取以保护设备内存。")
            }
            val bytes = body.byteStream().use { input ->
                BoundedTextPayload.readBytes(
                    input,
                    resourceLabel = "YouTube 字幕响应",
                    checkActive = { ownerJob?.ensureActive() },
                )
            }
            String(bytes, Charsets.UTF_8)
        }
    }

    private fun initOnce() {
        if (!inited) {
            synchronized(this) {
                if (!inited) {
                    org.schabi.newpipe.extractor.NewPipe.init(SimpleDownloader)
                    inited = true
                }
            }
        }
    }
