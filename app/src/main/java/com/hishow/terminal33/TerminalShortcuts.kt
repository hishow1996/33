package com.hishow.terminal33

/** Centralized mobile-terminal key sequences. */
object TerminalShortcuts {
    const val TAB = "\t"
    const val ESC = "\u001b"
    const val CTRL_C = "\u0003"
    const val CTRL_D = "\u0004"
    const val CTRL_L = "\u000c"
    const val CTRL_Z = "\u001a"
    const val CTRL_A = "\u0001"
    const val CTRL_E = "\u0005"
    const val CTRL_W = "\u0017"
    const val CTRL_U = "\u0015"
    const val CTRL_K = "\u000b"
    const val UP = "\u001b[A"
    const val DOWN = "\u001b[B"
    const val LEFT = "\u001b[D"
    const val RIGHT = "\u001b[C"
    const val HOME = "\u001b[H"
    const val END = "\u001b[F"
}
