package io.translatetube.local.yt

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test
import java.io.ByteArrayInputStream
import java.io.ByteArrayOutputStream
import java.util.zip.ZipEntry
import java.util.zip.ZipOutputStream

class YtDlpVersionPolicyTest {
    @Test
    fun choosesLatestStableVersionInsteadOfDevelopmentBuild() {
        val metadata = """
            {
              "info": {"version": "2026.10.10.233141.dev0"},
              "releases": {
                "2026.8.19": [{}],
                "2026.9.27.232945.dev0": [{}],
                "2026.3.17": [{}],
                "2025.12.8": [{}],
                "2026.10.10.233141.dev0": [{}],
                "2026.9.1rc1": [{}]
              }
            }
        """.trimIndent()
        assertEquals("2026.8.19", YtDlpVersionPolicy.latestStableFromPypiJson(metadata))
    }

    @Test
    fun readsInstalledVersionFromActualYtDlpCommandOutput() {
        assertEquals(
            "2026.10.10",
            YtDlpVersionPolicy.installedVersionFromOutput(
                """Python 3.12.0
2026.10.10
""",
            ),
        )
        assertEquals(
            "2026.10.10",
            YtDlpVersionPolicy.installedVersionFromOutput("yt-dlp version 2026.10.10"),
        )
        assertEquals(
            "2026.10.10",
            YtDlpVersionPolicy.installedVersionFromOutput("YT-DLP 2026.10.10"),
        )
        assertNull(
            YtDlpVersionPolicy.installedVersionFromOutput(
                """yt-dlp --version
2026.10.10.dev0
""",
            ),
        )
        assertNull(
            YtDlpVersionPolicy.installedVersionFromOutput("yt-dlp version 2026.10.10.233141.dev0"),
        )
        assertNull(YtDlpVersionPolicy.installedVersionFromOutput(""))
    }

    @Test
    fun acceptsOnlyStableDateTags() {
        assertTrue(YtDlpVersionPolicy.isStableTag("2026.8.19"))
        assertFalse(YtDlpVersionPolicy.isStableTag("2026.10.10.233141.dev0"))
        assertFalse(YtDlpVersionPolicy.isStableTag("2026.9.1rc1"))
    }

    @Test
    fun readsStableTagFromGithubRelease() {
        assertEquals(
            "2026.8.19",
            YtDlpVersionPolicy.stableGitHubTag("""{"tag_name":"2026.8.19"}"""),
        )
        assertNull(YtDlpVersionPolicy.stableGitHubTag("""{"tag_name":"2026.10.10.233141.dev0"}"""))
    }

    @Test
    fun readsStableTagFromLatestReleaseRedirect() {
        assertEquals(
            "2026.8.19",
            YtDlpVersionPolicy.stableTagFromReleasePath("/yt-dlp/yt-dlp/releases/tag/2026.8.19"),
        )
        assertNull(
            YtDlpVersionPolicy.stableTagFromReleasePath("/yt-dlp/yt-dlp/releases/latest"),
        )
    }

    @Test
    fun installedBuildAlsoAcceptsNightlyAndDevVersions() {
        assertEquals("2025.04.30.123456", YtDlpVersionPolicy.installedBuildFromOutput("2025.04.30.123456\n"))
        assertEquals(
            "2026.10.10.233141.dev0",
            YtDlpVersionPolicy.installedBuildFromOutput("yt-dlp version 2026.10.10.233141.dev0"),
        )
        assertEquals("2026.8.19", YtDlpVersionPolicy.installedBuildFromOutput("2026.8.19"))
        assertNull(YtDlpVersionPolicy.installedBuildFromOutput("Traceback (most recent call last):"))
        assertNull(YtDlpVersionPolicy.installedBuildFromOutput(""))
        assertTrue(YtDlpVersionPolicy.isInstalledBuild("2025.04.30.123456"))
        assertFalse(YtDlpVersionPolicy.isInstalledBuild("not-a-version"))
    }

    @Test
    fun reportsUpdateOnlyWhenInstalledReleaseDateIsOlder() {
        assertTrue(YtDlpVersionPolicy.isUpdateAvailable("2025.04.30", "2026.8.19"))
        assertFalse(YtDlpVersionPolicy.isUpdateAvailable("2026.8.19", "2026.8.19"))
        assertFalse(YtDlpVersionPolicy.isUpdateAvailable("2026.8.19.123456", "2026.8.19"))
        assertFalse(YtDlpVersionPolicy.isUpdateAvailable("2026.10.10.233141", "2026.8.19"))
        assertFalse(YtDlpVersionPolicy.isUpdateAvailable(null, "2026.8.19"))
        assertFalse(YtDlpVersionPolicy.isUpdateAvailable("2026.8.19", null))
    }

    @Test
    fun readsVersionFromZipappThatStartsWithShebang() {
        val archive = zipapp(
            "#!/usr/bin/env python3\n",
            "yt_dlp/__init__.py" to "print('hello')\n",
            "yt_dlp/version.py" to
                "# Autogenerated by devscripts/update-version.py\n\n__version__ = '2025.04.30'\n\nRELEASE_GIT_HEAD = 'abc'\n",
        )
        assertEquals("2025.04.30", YtDlpVersionPolicy.versionFromZipapp(ByteArrayInputStream(archive)))
    }

    @Test
    fun zipappWithoutVersionModuleOrNotAZipReturnsNull() {
        val archive = zipapp("#!/usr/bin/env python3\n", "yt_dlp/__init__.py" to "print('hello')\n")
        assertNull(YtDlpVersionPolicy.versionFromZipapp(ByteArrayInputStream(archive)))
        assertNull(YtDlpVersionPolicy.versionFromZipapp(ByteArrayInputStream("not a zip".toByteArray())))
        assertNull(YtDlpVersionPolicy.versionFromZipapp(ByteArrayInputStream(ByteArray(0))))
    }

    private fun zipapp(shebang: String, vararg entries: Pair<String, String>): ByteArray {
        val buffer = ByteArrayOutputStream()
        buffer.write(shebang.toByteArray(Charsets.UTF_8))
        ZipOutputStream(buffer).use { zip ->
            entries.forEach { (name, body) ->
                zip.putNextEntry(ZipEntry(name))
                zip.write(body.toByteArray(Charsets.UTF_8))
                zip.closeEntry()
            }
        }
        return buffer.toByteArray()
    }

}
