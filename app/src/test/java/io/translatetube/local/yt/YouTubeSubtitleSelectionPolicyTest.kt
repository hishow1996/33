package io.translatetube.local.yt

import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class YouTubeSubtitleSelectionPolicyTest {
    @Test
    fun koreanOriginalAudioPrioritizesKoreanOverEnglishCaptions() {
        assertEquals(1, YouTubeSubtitleSelectionPolicy.rank("ko-KR", "ko", isAutoGenerated = true))
        assertEquals(2, YouTubeSubtitleSelectionPolicy.rank("ko-KR", "en", isAutoGenerated = false))
        assertEquals(0, YouTubeSubtitleSelectionPolicy.rank("ko-KR", "ko-KR", isAutoGenerated = false))
    }

    @Test
    fun mismatchedLanguageCaptionIsNotEligibleWhenOriginalAudioLanguageIsKnown() {
        assertTrue(YouTubeSubtitleSelectionPolicy.matchesSourceLanguage("ko-KR", "ko"))
        assertFalse(YouTubeSubtitleSelectionPolicy.matchesSourceLanguage("ko-KR", "en"))
        assertFalse(YouTubeSubtitleSelectionPolicy.matchesSourceLanguage("ko-KR", "zh-Hans"))
        assertFalse(YouTubeSubtitleSelectionPolicy.matchesSourceLanguage(null, "ko"))
    }

    @Test
    fun matchingAutoCaptionBeatsUnrelatedManualCaption() {
        val koreanAutoRank = YouTubeSubtitleSelectionPolicy.rank("ko", "ko", isAutoGenerated = true)
        val englishManualRank = YouTubeSubtitleSelectionPolicy.rank("ko", "en", isAutoGenerated = false)
        assertTrue(koreanAutoRank < englishManualRank)
    }

    @Test
    fun manualCaptionWinsWhenBothTracksMatchOriginalAudio() {
        assertTrue(
            YouTubeSubtitleSelectionPolicy.rank("ja-JP", "ja", isAutoGenerated = false) <
                YouTubeSubtitleSelectionPolicy.rank("ja-JP", "ja", isAutoGenerated = true),
        )
    }

    @Test
    fun originalAudioLanguageHasPriorityOverStreamLanguageAndOtherAudioLocales() {
        assertEquals(
            "ko",
            YouTubeSubtitleSelectionPolicy.sourceLanguageHint(
                originalAudioLanguageTags = listOf("ko-KR"),
                streamLanguageTag = "en-US",
                fallbackAudioLanguageTags = listOf("en-US"),
            ),
        )
    }

    @Test
    fun iso639ThreeLetterAudioTagsMatchTwoLetterCaptionTags() {
        assertEquals("ko", YouTubeSubtitleSelectionPolicy.normalizeLanguageCode("kor"))
        assertEquals("ko", YouTubeSubtitleSelectionPolicy.normalizeLanguageCode("ko-KR"))
        assertEquals("zh", YouTubeSubtitleSelectionPolicy.normalizeLanguageCode("cmn-Hans"))
        assertEquals(true, YouTubeSubtitleSelectionPolicy.matchesSourceLanguage("kor", "ko"))
        assertEquals(true, YouTubeSubtitleSelectionPolicy.matchesSourceLanguage("eng", "en"))
    }

    @Test
    fun conflictingAudioLanguagesWithoutOriginalTrackMarkerStayUnknown() {
        assertNull(
            YouTubeSubtitleSelectionPolicy.sourceLanguageHint(
                originalAudioLanguageTags = emptyList(),
                streamLanguageTag = null,
                fallbackAudioLanguageTags = listOf("en-US", "ko-KR", "ko"),
            ),
        )
        assertNull(
            YouTubeSubtitleSelectionPolicy.sourceLanguageHint(
                originalAudioLanguageTags = listOf("en-US", "ko-KR"),
                streamLanguageTag = "en-US",
                fallbackAudioLanguageTags = listOf("en-US"),
            ),
        )
    }

    @Test
    fun missingLocaleOnExplicitOriginalTrackDoesNotBorrowAnotherTracksLanguage() {
        assertNull(
            YouTubeSubtitleSelectionPolicy.sourceLanguageHint(
                originalAudioLanguageTags = emptyList(),
                streamLanguageTag = null,
                fallbackAudioLanguageTags = listOf("en-US"),
                originalAudioTrackPresent = true,
            ),
        )
        assertEquals(
            "ko",
            YouTubeSubtitleSelectionPolicy.sourceLanguageHint(
                originalAudioLanguageTags = emptyList(),
                streamLanguageTag = "ko-KR",
                fallbackAudioLanguageTags = listOf("en-US"),
                originalAudioTrackPresent = true,
            ),
        )
    }

    @Test
    fun streamLanguageIsUsedWhenOriginalAudioMetadataIsUnavailable() {
        assertEquals(
            "ja",
            YouTubeSubtitleSelectionPolicy.sourceLanguageHint(
                originalAudioLanguageTags = emptyList(),
                streamLanguageTag = "ja-JP",
                fallbackAudioLanguageTags = listOf("en-US"),
            ),
        )
    }

    @Test
    fun subtitleSnapshotValidationRejectsWrongOrUnverifiableLanguage() {
        assertTrue(
            YouTubeSubtitleSelectionPolicy.shouldInvalidateSubtitleSnapshot("ko", "en", "en"),
        )
        assertTrue(
            YouTubeSubtitleSelectionPolicy.shouldInvalidateSubtitleSnapshot("ko", "ko", "en"),
        )
        assertTrue(
            YouTubeSubtitleSelectionPolicy.shouldInvalidateSubtitleSnapshot("ko", "auto", "auto"),
        )
        assertFalse(
            YouTubeSubtitleSelectionPolicy.shouldInvalidateSubtitleSnapshot("ko", "ko-KR", "ko"),
        )
        assertFalse(
            YouTubeSubtitleSelectionPolicy.shouldInvalidateSubtitleSnapshot("ko", "auto", "ko"),
        )
        assertTrue(
            YouTubeSubtitleSelectionPolicy.shouldInvalidateSubtitleSnapshot(null, "en", "en"),
        )
    }

    @Test
    fun englishIsNotSpecialWhenSourceLanguageIsUnknown() {
        assertEquals(
            YouTubeSubtitleSelectionPolicy.rank(null, "ko", isAutoGenerated = false),
            YouTubeSubtitleSelectionPolicy.rank(null, "en", isAutoGenerated = false),
        )
        assertEquals(0, YouTubeSubtitleSelectionPolicy.rank("und", "en", isAutoGenerated = false))
        assertNull(YouTubeSubtitleSelectionPolicy.normalizeLanguageCode("und"))
        assertNull(YouTubeSubtitleSelectionPolicy.normalizeLanguageCode("auto"))
    }
}
