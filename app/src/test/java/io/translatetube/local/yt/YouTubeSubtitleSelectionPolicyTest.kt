package io.translatetube.local.yt

import org.junit.Assert.assertEquals
import org.junit.Assert.assertNull
import org.junit.Test

class YouTubeSubtitleSelectionPolicyTest {
    @Test
    fun koreanOriginalAudioPrioritizesKoreanOverEnglishCaptions() {
        assertEquals(1, YouTubeSubtitleSelectionPolicy.rank("ko-KR", "ko", isAutoGenerated = true))
        assertEquals(2, YouTubeSubtitleSelectionPolicy.rank("ko-KR", "en", isAutoGenerated = false))
        assertEquals(0, YouTubeSubtitleSelectionPolicy.rank("ko-KR", "ko-KR", isAutoGenerated = false))
    }

    @Test
    fun matchingAutoCaptionBeatsUnrelatedManualCaption() {
        val koreanAutoRank = YouTubeSubtitleSelectionPolicy.rank("ko", "ko", isAutoGenerated = true)
        val englishManualRank = YouTubeSubtitleSelectionPolicy.rank("ko", "en", isAutoGenerated = false)
        assertEquals(true, koreanAutoRank < englishManualRank)
    }

    @Test
    fun manualCaptionWinsWhenBothTracksMatchOriginalAudio() {
        assertEquals(
            true,
            YouTubeSubtitleSelectionPolicy.rank("ja-JP", "ja", isAutoGenerated = false) <
                YouTubeSubtitleSelectionPolicy.rank("ja-JP", "ja", isAutoGenerated = true),
        )
    }

    @Test
    fun originalAudioLanguageHasPriorityOverStreamLanguageAndOtherAudioLocales() {
        assertEquals(
            "ko",
            YouTubeSubtitleSelectionPolicy.sourceLanguageHint(
                originalAudioLanguageTags = listOf("ko-KR"),
                streamLanguageTag = "en-US",
                fallbackAudioLanguageTags = listOf("en-US"),
            ),
        )
    }

    @Test
    fun streamLanguageIsUsedWhenOriginalAudioMetadataIsUnavailable() {
        assertEquals(
            "ja",
            YouTubeSubtitleSelectionPolicy.sourceLanguageHint(
                originalAudioLanguageTags = emptyList(),
                streamLanguageTag = "ja-JP",
                fallbackAudioLanguageTags = listOf("en-US"),
            ),
        )
    }

    @Test
    fun englishIsNotSpecialWhenSourceLanguageIsUnknown() {
        assertEquals(
            YouTubeSubtitleSelectionPolicy.rank(null, "ko", isAutoGenerated = false),
            YouTubeSubtitleSelectionPolicy.rank(null, "en", isAutoGenerated = false),
        )
        assertEquals(0, YouTubeSubtitleSelectionPolicy.rank("und", "en", isAutoGenerated = false))
        assertNull(YouTubeSubtitleSelectionPolicy.normalizeLanguageCode("und"))
        assertNull(YouTubeSubtitleSelectionPolicy.normalizeLanguageCode("auto"))
    }
}
